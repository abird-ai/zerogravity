#[derive(Clone, Copy)]
pub(super) struct Compensated {
    pub(super) high: f32,
    pub(super) low: f32,
}

impl Compensated {
    // Source dfadd_vf2_vf_vf; operand order is part of this closed algorithm.
    pub(super) fn sum(left: f32, right: f32) -> Self {
        let high = left + right;
        Self {
            high,
            low: (left - high) + right,
        }
    }

    pub(super) fn add_pair(self, other: Self) -> Self {
        let high = self.high + other.high;
        Self {
            high,
            low: (((self.high - high) + other.high) + self.low) + other.low,
        }
    }

    pub(super) fn add_scalar(self, other: f32) -> Self {
        let high = self.high + other;
        Self {
            high,
            low: ((self.high - high) + other) + self.low,
        }
    }

    pub(super) fn multiply_scalar(self, other: f32) -> Self {
        let high = self.high * other;
        Self {
            high,
            low: self.low.mul_add(other, self.high.mul_add(other, -high)),
        }
    }

    pub(super) fn scale(self, other: f32) -> Self {
        Self {
            high: self.high * other,
            low: self.low * other,
        }
    }

    pub(super) fn divide(self, denominator: Self) -> Self {
        // Source dfdiv FMA_SP path, including both numerator components.
        let reciprocal = 1.0f32 / denominator.high;
        let high = self.high * reciprocal;
        let residual = reciprocal.mul_add(self.high, -high);
        let correction =
            (-denominator.low).mul_add(reciprocal, (-denominator.high).mul_add(reciprocal, 1.0));
        Self {
            high,
            low: high.mul_add(correction, self.low.mul_add(reciprocal, residual)),
        }
    }
}

// Remaining exact df.h FMA_SP operations used by expk2f/xtanhf.
impl Compensated {
    pub(super) fn add_general_scalar(self, other: f32) -> Self {
        let high = self.high + other;
        let v = high - self.high;
        let t = (self.high - (high - v)) + (other - v);
        Self {
            high,
            low: t + self.low,
        }
    }
    pub(super) fn add_general_pair(self, other: Self) -> Self {
        let high = self.high + other.high;
        let v = high - self.high;
        let t = (self.high - (high - v)) + (other.high - v);
        Self {
            high,
            low: t + (self.low + other.low),
        }
    }
    pub(super) fn scalar_plus_fast(value: f32, other: Self) -> Self {
        let high = value + other.high;
        Self {
            high,
            low: ((value - high) + other.high) + other.low,
        }
    }
    pub(super) fn multiply_pair(self, other: Self) -> Self {
        let high = self.high * other.high;
        Self {
            high,
            low: self.high.mul_add(
                other.low,
                self.low
                    .mul_add(other.high, self.high.mul_add(other.high, -high)),
            ),
        }
    }
    pub(super) fn square(self) -> Self {
        let high = self.high * self.high;
        Self {
            high,
            low: (self.high + self.high).mul_add(self.low, self.high.mul_add(self.high, -high)),
        }
    }
    pub(super) fn reciprocal(self) -> Self {
        let high = 1.0 / self.high;
        Self {
            high,
            low: high * ((-self.low).mul_add(high, (-self.high).mul_add(high, 1.0))),
        }
    }
    pub(super) fn negate(self) -> Self {
        Self {
            high: -self.high,
            low: -self.low,
        }
    }
}
