const SPAN: usize = 16;
const MAX_ELEMENTS: usize = 1_048_576;

// Private lane of SLEEF's vector exp; not an aten.exp/provider implementation.
fn sleef_exp_finite_lane(input: f32) -> f32 {
    // Source applies these masks after arithmetic. Finite-only inputs permit
    // early selection, avoiding the SIMD indefinite-integer conversion cases.
    if input < -104.0 {
        return 0.0;
    }
    if input > 100.0 {
        return f32::INFINITY;
    }
    let quotient = (input * f32::from_bits(0x3fb8_aa3b)).round_ties_even() as i32;
    let quotient_f32 = quotient as f32;
    let remainder = quotient_f32.mul_add(-f32::from_bits(0x3f31_7200), input);
    let remainder = quotient_f32.mul_add(-f32::from_bits(0x35bf_be8e), remainder);
    let polynomial = f32::from_bits(0x3950_2bda)
        .mul_add(remainder, f32::from_bits(0x3ab6_96c9))
        .mul_add(remainder, f32::from_bits(0x3c08_88a6))
        .mul_add(remainder, f32::from_bits(0x3d2a_aa7a))
        .mul_add(remainder, f32::from_bits(0x3e2a_aaab))
        .mul_add(remainder, f32::from_bits(0x3f00_0000));
    let unscaled = 1.0 + (remainder * remainder).mul_add(polynomial, remainder);
    let first_exponent = quotient >> 1;
    let second_exponent = quotient - first_exponent;
    let first_scale = f32::from_bits(((first_exponent + 127) as u32) << 23);
    let second_scale = f32::from_bits(((second_exponent + 127) as u32) << 23);
    (unscaled * first_scale) * second_scale
}

/// Source-bound private FP32 SiLU proposal for one contiguous vector span.
/// Exact BF16-widened finite inputs only; positive length divisible16 excludes
/// Torch's different scalar-tail arithmetic. No model/profile eligibility.
pub fn silu_bf16_widened_f32_contiguous16(
    source: SourceIdentity,
    input: &[f32],
) -> Result<Vec<f32>> {
    if !source.is_bound() || input.is_empty() || !input.len().is_multiple_of(SPAN) {
        return Err(Error::Malformed(
            "pinned CPU SiLU source/contiguous span".into(),
        ));
    }
    if input.len() > MAX_ELEMENTS {
        return Err(Error::Limit("pinned CPU SiLU element bound".into()));
    }
    if input
        .iter()
        .any(|value| !value.is_finite() || value.to_bits() & 0xffff != 0)
    {
        return Err(Error::Malformed(
            "pinned CPU SiLU requires finite exact BF16-widened inputs".into(),
        ));
    }
    let output = input
        .iter()
        .map(|&value| value / (1.0 + sleef_exp_finite_lane(-value)))
        .collect::<Vec<_>>();
    if output.iter().any(|value| !value.is_finite()) {
        return Err(Error::Malformed("nonfinite pinned CPU SiLU output".into()));
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> SourceIdentity {
        SourceIdentity::for_new_allocation().unwrap()
    }

    fn words(input: &[u32]) -> Vec<f32> {
        input.iter().map(|&word| f32::from_bits(word)).collect()
    }

    #[test]
    fn authentic_source_gate_counterexamples_match_raw_fp32_words() {
        // Untouched original .8B layer0, tokens11/353. Every selected word
        // differs from the earlier scalar-libm observation, before BF16 cast.
        let pairs = include_str!("transcendentals_silu_golden.txt")
            .lines()
            .filter(|line| !line.starts_with('#') && !line.is_empty())
            .map(|line| {
                let mut parts = line.split_whitespace();
                let input = u32::from_str_radix(parts.next().unwrap(), 16).unwrap();
                let output = u32::from_str_radix(parts.next().unwrap(), 16).unwrap();
                assert!(parts.next().is_none());
                (input, output)
            })
            .collect::<Vec<_>>();
        assert_eq!(pairs.len(), 32);
        let input = pairs
            .iter()
            .map(|&(input, _)| f32::from_bits(input))
            .collect::<Vec<_>>();
        let actual = silu_bf16_widened_f32_contiguous16(source(), &input).unwrap();
        for (index, (actual, &(_, expected))) in actual.iter().zip(&pairs).enumerate() {
            assert_eq!(actual.to_bits(), expected, "source word {index}");
        }
    }

    #[test]
    fn signed_zero_gradual_underflow_and_saturation_follow_source_arithmetic() {
        let input = words(&[
            0,
            0x8000_0000,
            0x0001_0000,
            0x8001_0000,
            0x0080_0000,
            0x8080_0000,
            0x7f7f_0000,
            0xff7f_0000,
            0x4300_0000,
            0xc300_0000,
            0x4380_0000,
            0xc380_0000,
            0x4f80_0000,
            0xcf80_0000,
            0,
            0x8000_0000,
        ]);
        let expected = [
            0,
            0x8000_0000,
            0x0000_8000,
            0x8000_8000,
            0x0040_0000,
            0x8040_0000,
            0x7f7f_0000,
            0x8000_0000,
            0x4300_0000,
            0x8000_0000,
            0x4380_0000,
            0x8000_0000,
            0x4f80_0000,
            0x8000_0000,
            0,
            0x8000_0000,
        ];
        let output = silu_bf16_widened_f32_contiguous16(source(), &input).unwrap();
        for (index, (actual, expected)) in output.iter().zip(expected).enumerate() {
            assert_eq!(actual.to_bits(), expected, "edge word {index}");
        }
    }

    #[test]
    fn source_shape_encoding_and_finite_guards_reject_before_math() {
        let normal = [1.0; SPAN];
        assert!(matches!(
            silu_bf16_widened_f32_contiguous16(SourceIdentity::unbound(), &normal),
            Err(Error::Malformed(_))
        ));
        for invalid in [&[][..], &normal[..1], &normal[..15]] {
            assert!(matches!(
                silu_bf16_widened_f32_contiguous16(source(), invalid),
                Err(Error::Malformed(_))
            ));
        }
        let large = vec![1.0; MAX_ELEMENTS + SPAN];
        assert!(matches!(
            silu_bf16_widened_f32_contiguous16(source(), &large),
            Err(Error::Limit(_))
        ));
        for invalid in [
            f32::from_bits(0x3f80_0001),
            f32::NAN,
            f32::INFINITY,
            f32::NEG_INFINITY,
        ] {
            let mut values = normal;
            values[SPAN - 1] = invalid;
            assert!(matches!(
                silu_bf16_widened_f32_contiguous16(source(), &values),
                Err(Error::Malformed(_))
            ));
            assert_eq!(values[SPAN - 1].to_bits(), invalid.to_bits());
        }
    }
}
