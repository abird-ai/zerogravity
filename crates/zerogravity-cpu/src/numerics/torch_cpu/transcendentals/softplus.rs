use super::{MAX_ELEMENTS, SPAN, sleef_exp_finite_lane};
use crate::accelerator::SourceIdentity;
use crate::{Error, Result};

use super::compensated::Compensated;

// Only the nonlinear softplus branch calls this lane: exp(x), x<=20, is
// nonnegative and below2^30. dp1 is normal, and SLEEF's very-large-log and
// negative-domain branches cannot select. No general log1p API is exposed.
fn log1p_nonnegative_lane(input: f32) -> f32 {
    let plus_one = input + 1.0;
    let scaled = plus_one * f32::from_bits(0x3faa_aaab);
    let exponent = ((scaled.to_bits() >> 23) & 0xff) as i32 - 127;
    let power = f32::from_bits(((127 - exponent) as u32) << 23);
    let mantissa = input.mul_add(power, power - 1.0);
    let mut accumulated = Compensated {
        high: f32::from_bits(0x3f31_7218),
        low: f32::from_bits(0xb102_e308),
    }
    .multiply_scalar(exponent as f32);
    let ratio = Compensated {
        high: mantissa,
        low: 0.0,
    }
    .divide(Compensated::sum(2.0, mantissa));
    let squared = ratio.high * ratio.high;
    let polynomial = f32::from_bits(0x3e9a_ff5c)
        .mul_add(squared, f32::from_bits(0x3ecc_99ca))
        .mul_add(squared, f32::from_bits(0x3f2a_aada));
    accumulated = accumulated.add_pair(ratio.scale(2.0));
    accumulated = accumulated.add_scalar((squared * ratio.high) * polynomial);
    accumulated.high + accumulated.low
}

/// Pure source-bound FP32 softplus proposal for one contiguous vector span.
/// Fixed beta1/threshold20; finite general FP32 input, positive length
/// divisible16/max1M. No BF16 cast, scalar-tail or source/profile promotion.
pub fn softplus_beta1_threshold20_f32_contiguous16(
    source: SourceIdentity,
    input: &[f32],
) -> Result<Vec<f32>> {
    if !source.is_bound() || input.is_empty() || !input.len().is_multiple_of(SPAN) {
        return Err(Error::Malformed(
            "pinned CPU softplus source/contiguous span".into(),
        ));
    }
    if input.len() > MAX_ELEMENTS {
        return Err(Error::Limit("pinned CPU softplus element bound".into()));
    }
    if input.iter().any(|value| !value.is_finite()) {
        return Err(Error::Malformed(
            "nonfinite pinned CPU softplus input".into(),
        ));
    }
    let output = input
        .iter()
        .map(|&value| {
            if value > 20.0 {
                value
            } else {
                // Multiplication/division by beta1 are exact finite identities.
                log1p_nonnegative_lane(sleef_exp_finite_lane(value))
            }
        })
        .collect::<Vec<_>>();
    if output.iter().any(|value| !value.is_finite()) {
        return Err(Error::Malformed(
            "nonfinite pinned CPU softplus output".into(),
        ));
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn source() -> SourceIdentity {
        SourceIdentity::for_new_allocation().unwrap()
    }

    #[test]
    fn actual_original_biased_alpha_matches_all_raw_fp32_golden_words() {
        let pairs = include_str!("softplus_golden.txt")
            .lines()
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .map(|line| {
                let mut words = line.split_whitespace();
                let input = u32::from_str_radix(words.next().unwrap(), 16).unwrap();
                let output = u32::from_str_radix(words.next().unwrap(), 16).unwrap();
                assert!(words.next().is_none());
                (input, output)
            })
            .collect::<Vec<_>>();
        assert_eq!(pairs.len(), 32);
        assert!(pairs.iter().any(|&(input, _)| input & 0xffff != 0));
        let input = pairs
            .iter()
            .map(|&(word, _)| f32::from_bits(word))
            .collect::<Vec<_>>();
        let output = softplus_beta1_threshold20_f32_contiguous16(source(), &input).unwrap();
        for (index, (actual, &(_, expected))) in output.iter().zip(&pairs).enumerate() {
            assert_eq!(actual.to_bits(), expected, "original word {index}");
        }
    }

    #[test]
    fn compensation_retains_a_rounding_residual_before_later_cancellation() {
        let partial = Compensated::sum(2.0, f32::from_bits(0x3380_0000));
        assert_eq!(partial.high.to_bits(), 2.0f32.to_bits());
        assert_eq!(partial.low.to_bits(), 0x3380_0000);
        let cancelled = partial.add_scalar(-2.0);
        assert_eq!(cancelled.high.to_bits(), 0);
        assert_eq!((cancelled.high + cancelled.low).to_bits(), 0x3380_0000);
    }

    #[test]
    fn finite_linear_saturation_and_zero_sign_boundaries_remain_explicit() {
        let words = [
            0x41a0_0001,
            0x41a0_0002,
            0x42c8_0001,
            0x7f7f_ffff,
            0xc2d2_0000,
            0xc300_0000,
            0xcf80_0000,
            0xff7f_ffff,
            0,
            0x8000_0000,
            1,
            0x8000_0001,
            0x007f_ffff,
            0x807f_ffff,
            0x0080_0000,
            0x8080_0000,
        ];
        let input = words.map(f32::from_bits);
        let output = softplus_beta1_threshold20_f32_contiguous16(source(), &input).unwrap();
        for index in 0..4 {
            assert_eq!(output[index].to_bits(), words[index]);
        }
        assert!(output[4..8].iter().all(|value| value.to_bits() == 0));
        // All these exp inputs round to the same1 before compensated log1p.
        assert!(
            output[8..]
                .iter()
                .all(|value| value.to_bits() == output[8].to_bits())
        );
        assert!(output[8].is_sign_positive() && output[8] > 0.0);
    }

    #[test]
    fn source_shape_bounds_and_nonfinite_inputs_refuse_before_math() {
        let valid = [1.0001; SPAN];
        assert!(softplus_beta1_threshold20_f32_contiguous16(source(), &valid).is_ok());
        assert!(matches!(
            softplus_beta1_threshold20_f32_contiguous16(SourceIdentity::unbound(), &valid),
            Err(Error::Malformed(_))
        ));
        for invalid in [&[][..], &valid[..1], &valid[..SPAN - 1]] {
            assert!(matches!(
                softplus_beta1_threshold20_f32_contiguous16(source(), invalid),
                Err(Error::Malformed(_))
            ));
        }
        let large = vec![1.0; MAX_ELEMENTS + SPAN];
        assert!(matches!(
            softplus_beta1_threshold20_f32_contiguous16(source(), &large),
            Err(Error::Limit(_))
        ));
        for invalid in [f32::NAN, f32::INFINITY, f32::NEG_INFINITY] {
            let mut values = valid;
            values[SPAN - 1] = invalid;
            assert!(matches!(
                softplus_beta1_threshold20_f32_contiguous16(source(), &values),
                Err(Error::Malformed(_))
            ));
            assert_eq!(values[SPAN - 1].to_bits(), invalid.to_bits());
        }
    }
}
