use super::*;

fn source() -> SourceIdentity {
    SourceIdentity::for_new_allocation().unwrap()
}

#[test]
fn masks_and_finite_subtraction_overflow_keep_one_hot_positive_zero() {
    // Analytical identities only; not a Torch parity receipt.
    for width in [1, 2, 7, 8, 9, 31, 32, 33, 255, 256, 257, 511, 512] {
        for peak in [0, width / 2, width - 1] {
            let mut input = vec![-f32::MAX; width * 2];
            input[peak] = f32::MAX;
            input[width..].fill(f32::NEG_INFINITY);
            input[width + peak] = -0.0;
            let output = softmax_f32_lastdim_avx2(source(), &input, width).unwrap();
            for row in output.chunks_exact(width) {
                for (column, value) in row.iter().enumerate() {
                    let expected = if column == peak { 1.0f32 } else { 0.0 };
                    assert_eq!(
                        value.to_bits(),
                        expected.to_bits(),
                        "{width}/{peak}/{column}"
                    );
                }
            }
        }
    }
}

#[test]
fn opposite_signed_zero_rows_have_exact_power_of_two_probabilities() {
    for width in [1usize, 2, 4, 8, 16, 32, 64, 128, 256, 512] {
        let input = (0..width * 2)
            .map(|index| if index.is_multiple_of(2) { -0.0 } else { 0.0 })
            .collect::<Vec<_>>();
        let output = softmax_f32_lastdim_avx2(source(), &input, width).unwrap();
        let expected = 1.0f32 / width as f32;
        assert_eq!(output.len(), input.len());
        assert!(
            output
                .iter()
                .all(|value| value.to_bits() == expected.to_bits())
        );
    }
}

#[test]
fn source_geometry_and_element_guards_refuse() {
    assert!(softmax_f32_lastdim_avx2(SourceIdentity::unbound(), &[0.0], 1).is_err());
    assert!(softmax_f32_lastdim_avx2(source(), &[], 1).is_err());
    assert!(softmax_f32_lastdim_avx2(source(), &[0.0], 0).is_err());
    assert!(softmax_f32_lastdim_avx2(source(), &[0.0; 513], 513).is_err());
    assert!(softmax_f32_lastdim_avx2(source(), &[0.0; 9], 8).is_err());
    let oversized = vec![0.0; MAX_ELEMENTS + 1];
    assert!(matches!(
        softmax_f32_lastdim_avx2(source(), &oversized, 1),
        Err(Error::Limit(_))
    ));
}

#[test]
fn every_row_is_validated_and_unknown_masks_refuse() {
    for invalid in [f32::NAN, f32::from_bits(0xffc0_0001), f32::INFINITY] {
        assert!(softmax_f32_lastdim_avx2(source(), &[0.0, 0.0, invalid, 0.0], 2).is_err());
    }
    assert!(
        softmax_f32_lastdim_avx2(
            source(),
            &[0.0, 0.0, f32::NEG_INFINITY, f32::NEG_INFINITY],
            2
        )
        .is_err()
    );
    assert!(softmax_f32_lastdim_avx2(source(), &[f32::NEG_INFINITY], 1).is_err());
}

struct Cursor<'a>(&'a [u8]);
impl<'a> Cursor<'a> {
    fn take(&mut self, count: usize) -> &'a [u8] {
        assert!(count <= self.0.len(), "truncated public softmax fixture");
        let (head, tail) = self.0.split_at(count);
        self.0 = tail;
        head
    }
    fn u32(&mut self) -> u32 {
        u32::from_le_bytes(self.take(4).try_into().unwrap())
    }
    fn words(&mut self, count: usize) -> Vec<f32> {
        self.take(count.checked_mul(4).unwrap())
            .chunks_exact(4)
            .map(|word| f32::from_bits(u32::from_le_bytes(word.try_into().unwrap())))
            .collect()
    }
}

// Raw independent public outputs, never values generated by this kernel.
fn replay_public_fixture(bytes: &[u8]) -> (usize, usize, usize) {
    assert!(bytes.len() <= 64 * 1024 * 1024);
    let mut cursor = Cursor(bytes);
    assert_eq!(cursor.take(8), b"ZGSMX001");
    let count = cursor.u32() as usize;
    assert!((1..=4096).contains(&count));
    let mut matched = 0usize;
    let mut refused = 0usize;
    for _ in 0..count {
        let label_bytes = cursor.u32() as usize;
        assert!((1..=256).contains(&label_bytes));
        let label = std::str::from_utf8(cursor.take(label_bytes)).unwrap();
        let refusal = cursor.u32();
        let width = cursor.u32() as usize;
        let rows = cursor.u32() as usize;
        assert!((1..=MAX_WIDTH).contains(&width) && rows > 0);
        let elements = rows
            .checked_mul(width)
            .filter(|&n| n <= MAX_ELEMENTS)
            .unwrap();
        let input = cursor.words(elements);
        if refusal == 1 {
            assert!(
                softmax_f32_lastdim_avx2(source(), &input, width).is_err(),
                "{label}"
            );
            refused += 1;
        } else {
            assert_eq!(refusal, 0);
            let expected = cursor.words(elements);
            let actual = softmax_f32_lastdim_avx2(source(), &input, width).unwrap();
            assert_eq!(actual.len(), expected.len(), "{label}");
            for (index, (actual, expected)) in actual.iter().zip(&expected).enumerate() {
                assert_eq!(actual.to_bits(), expected.to_bits(), "{label} word{index}");
            }
            matched += elements;
        }
    }
    assert!(matched > 0);
    assert_eq!(refused, 3);
    assert!(cursor.0.is_empty(), "trailing public softmax fixture bytes");
    eprintln!("PUBLIC_SOFTMAX_EXACT cases{count} words{matched} refusals{refused}");
    (count, matched, refused)
}

#[test]
fn committed_public_operator_golden_is_exact() {
    // Authenticated byte-only compact export; provenance in golden.json.
    assert_eq!(
        replay_public_fixture(include_bytes!("golden.bin")),
        (72, 11_280, 3)
    );
}

#[test]
#[ignore = "requires authenticated root public-operator fixture in ZEROGRAVITY_SOFTMAX_FIXTURE"]
fn authenticated_public_operator_fixture() {
    let path = std::env::var_os("ZEROGRAVITY_SOFTMAX_FIXTURE").expect("root fixture path required");
    let bytes = std::fs::read(path).unwrap();
    replay_public_fixture(&bytes);
}
