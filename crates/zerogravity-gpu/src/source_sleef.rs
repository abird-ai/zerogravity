use crate::source_arithmetic::{add, bf16, div, fused, mul, neg, sub};
use cubecl::prelude::*;

#[cube]
fn general_scalar(h: f32, l: f32, x: f32) -> (f32, f32) {
    let high = add(h, x);
    let v = sub(high, h);
    let t = add(sub(h, sub(high, v)), sub(x, v));
    (high, add(t, l))
}
#[cube]
fn general_pair(h: f32, l: f32, x: f32, y: f32) -> (f32, f32) {
    let high = add(h, x);
    let v = sub(high, h);
    let t = add(sub(h, sub(high, v)), sub(x, v));
    (high, add(t, add(l, y)))
}
#[cube]
fn fast_pair(h: f32, l: f32, x: f32, y: f32) -> (f32, f32) {
    let high = add(h, x);
    (high, add(add(add(sub(h, high), x), l), y))
}
#[cube]
fn pair_scalar_mul(h: f32, l: f32, x: f32) -> (f32, f32) {
    let high = mul(h, x);
    (high, fused(l, x, fused(h, x, neg(high))))
}
#[cube]
fn pair_mul(h: f32, l: f32, x: f32, y: f32) -> (f32, f32) {
    let high = mul(h, x);
    (high, fused(h, y, fused(l, x, fused(h, x, neg(high)))))
}
#[cube]
fn square(h: f32, l: f32) -> (f32, f32) {
    let high = mul(h, h);
    (high, fused(add(h, h), l, fused(h, h, neg(high))))
}
#[cube]
fn reciprocal(h: f32, l: f32) -> (f32, f32) {
    let high = div(1.0f32, h);
    (
        high,
        mul(high, fused(neg(l), high, fused(neg(h), high, 1.0f32))),
    )
}
#[cube]
fn pair_div(h: f32, l: f32, x: f32, y: f32) -> (f32, f32) {
    let r = div(1.0f32, x);
    let high = mul(h, r);
    let residual = fused(r, h, neg(high));
    let correction = fused(neg(y), r, fused(neg(x), r, 1.0f32));
    (high, fused(high, correction, fused(l, r, residual)))
}
#[cube]
fn nearest_even(x: f32) -> i32 {
    // Inputs here are bounded to [-151,145]. No implementation-defined
    // float round intrinsic or source magic-bias rounding is substituted.
    let mut integer = i32::cast_from(x);
    let fraction = sub(x, f32::cast_from(integer));
    if fraction > 0.5f32 || (fraction == 0.5f32 && (integer & 1i32) != 0i32) {
        integer += 1i32;
    }
    if fraction < -0.5f32 || (fraction == -0.5f32 && (integer & 1i32) != 0i32) {
        integer -= 1i32;
    }
    integer
}
#[cube]
pub(crate) fn tanh(input: f32) -> f32 {
    let magnitude = f32::reinterpret(u32::reinterpret(input) & 0x7fffffffu32);
    let mut result = 1.0f32;
    if magnitude <= f32::reinterpret(0x410aa123u32) {
        let quotient = nearest_even(mul(magnitude, f32::reinterpret(0x3fb8aa3bu32)));
        let q = f32::cast_from(quotient);
        let (s0, s1) = general_scalar(
            magnitude,
            0.0f32,
            mul(q, neg(f32::reinterpret(0x3f317200u32))),
        );
        let (s0, s1) = general_scalar(s0, s1, mul(q, neg(f32::reinterpret(0x35bfbe8eu32))));
        let u = fused(
            f32::reinterpret(0x394fb7ffu32),
            s0,
            f32::reinterpret(0x3ab6bf7cu32),
        );
        let u = fused(u, s0, f32::reinterpret(0x3c08890du32));
        let u = fused(u, s0, f32::reinterpret(0x3d2aaa5cu32));
        let (t0, t1) = pair_scalar_mul(s0, s1, u);
        let (t0, t1) = general_scalar(t0, t1, f32::reinterpret(0x3e2aaaaau32));
        let (t0, t1) = pair_mul(s0, s1, t0, t1);
        let (t0, t1) = general_scalar(t0, t1, 0.5f32);
        let (sq0, sq1) = square(s0, s1);
        let (t0, t1) = pair_mul(sq0, sq1, t0, t1);
        let (t0, t1) = general_pair(s0, s1, t0, t1);
        let high = add(1.0f32, t0);
        let low = add(add(sub(1.0f32, high), t0), t1);
        let first = quotient >> 1i32;
        let second = quotient - first;
        let a = f32::reinterpret(u32::cast_from(first + 127i32) << 23u32);
        let b = f32::reinterpret(u32::cast_from(second + 127i32) << 23u32);
        let ph = mul(mul(high, a), b);
        let pl = mul(mul(low, a), b);
        let (nh, nl) = reciprocal(ph, pl);
        let (numerator0, numerator1) = fast_pair(ph, pl, neg(nh), neg(nl));
        let (denominator0, denominator1) = fast_pair(ph, pl, nh, nl);
        let (r0, r1) = pair_div(numerator0, numerator1, denominator0, denominator1);
        result = add(r0, r1);
    }
    f32::reinterpret(u32::reinterpret(result) ^ (u32::reinterpret(input) & 0x80000000u32))
}
#[cube]
pub(crate) fn gelu(x: f32) -> f32 {
    let cube = mul(mul(x, x), x);
    let inner = mul(
        f32::reinterpret(0x3f4c422au32),
        add(x, mul(0.044715f32, cube)),
    );
    bf16(mul(mul(0.5f32, x), add(1.0f32, tanh(inner))))
}
#[cube]
pub(crate) fn exp(input: f32) -> f32 {
    let mut output = 0.0f32;
    if input >= -104.0f32 {
        if input > 100.0f32 {
            output = f32::reinterpret(0x7f800000u32);
        } else {
            let quotient = nearest_even(mul(input, f32::reinterpret(0x3fb8aa3bu32)));
            let q = f32::cast_from(quotient);
            let r = fused(q, neg(f32::reinterpret(0x3f317200u32)), input);
            let r = fused(q, neg(f32::reinterpret(0x35bfbe8eu32)), r);
            let p = fused(
                f32::reinterpret(0x39502bdau32),
                r,
                f32::reinterpret(0x3ab696c9u32),
            );
            let p = fused(p, r, f32::reinterpret(0x3c0888a6u32));
            let p = fused(p, r, f32::reinterpret(0x3d2aaa7au32));
            let p = fused(p, r, f32::reinterpret(0x3e2aaaabu32));
            let p = fused(p, r, f32::reinterpret(0x3f000000u32));
            let unscaled = add(1.0f32, fused(mul(r, r), p, r));
            let first = quotient >> 1i32;
            let second = quotient - first;
            let a = f32::reinterpret(u32::cast_from(first + 127i32) << 23u32);
            let b = f32::reinterpret(u32::cast_from(second + 127i32) << 23u32);
            output = mul(mul(unscaled, a), b);
        }
    }
    output
}

/// Source SiLU has a private SLEEF vector exp; it is not aten standalone exp.
#[cube]
pub(crate) fn silu(x: f32) -> f32 {
    div(x, add(1.0f32, exp(neg(x))))
}

/// Source beta1/threshold20, no scalar-tail or general log1p permission.
#[cube]
pub(crate) fn softplus(x: f32) -> f32 {
    let mut result = x;
    if x <= 20.0f32 {
        let input = exp(x);
        let plus_one = add(input, 1.0f32);
        let scaled = mul(plus_one, f32::reinterpret(0x3faaaaabu32));
        let exponent = i32::cast_from((u32::reinterpret(scaled) >> 23u32) & 255u32) - 127i32;
        let power = f32::reinterpret(u32::cast_from(127i32 - exponent) << 23u32);
        let mantissa = fused(input, power, sub(power, 1.0f32));
        let (ah, al) = pair_scalar_mul(
            f32::reinterpret(0x3f317218u32),
            f32::reinterpret(0xb102e308u32),
            f32::cast_from(exponent),
        );
        let dh = add(2.0f32, mantissa);
        let dl = add(sub(2.0f32, dh), mantissa);
        let (rh, rl) = pair_div(mantissa, 0.0f32, dh, dl);
        let squared = mul(rh, rh);
        let p = fused(
            f32::reinterpret(0x3e9aff5cu32),
            squared,
            f32::reinterpret(0x3ecc99cau32),
        );
        let p = fused(p, squared, f32::reinterpret(0x3f2aaadau32));
        let (ah, al) = fast_pair(ah, al, mul(rh, 2.0f32), mul(rl, 2.0f32));
        let extra = mul(mul(squared, rh), p);
        let high = add(ah, extra);
        let low = add(add(sub(ah, high), extra), al);
        result = add(high, low);
    }
    result
}
